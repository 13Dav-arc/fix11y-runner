/**
 * Sanitizes markdown table cell content by wrapping unescaped HTML tag names
 * (e.g. <img>, <div>, <button type="button">, <input>, <label>) in code backticks
 * so GitHub Flavored Markdown renders them legibly rather than stripping or swallowing them.
 * Also escapes pipe characters to prevent breaking table syntax.
 */
export function formatCellText(text) {
  if (!text) return '-';
  return text
    .replace(/(?<!`)(<[a-zA-Z0-9_-]+(?: [^>]+)?>)(?!`)/g, '`$1`')
    .replace(/\|/g, '\\|');
}

export function formatPrBody({
  commitSha,
  appliedPatches = [],
  unresolvedAiIssues = [],
  diffSummary = '',
  testSummary = 'All tests passed',
}) {
  const shortSha = commitSha ? commitSha.slice(0, 7) : 'head';
  const totalApplied = appliedPatches.length;
  const safeCount = appliedPatches.filter(p => p.safety === 'safe').length;
  const cautionCount = appliedPatches.filter(p => p.safety === 'caution').length;

  const aiIssues = unresolvedAiIssues.filter(i => i.requiresAi !== false);
  const manualIssues = unresolvedAiIssues.filter(i => i.requiresAi === false);

  let body = `## ♿ fix11y Automated Accessibility Remediation

> Remediating WCAG 2.1/2.2 AA accessibility violations for commit \`${shortSha}\`.
> **Build Verification:** ✅ ${testSummary}.

---

### 📊 Remediation Overview

| Metric | Count |
| :--- | :--- |
| **Total Surgical Patches Applied** | **${totalApplied}** |
| 🟢 **Safe Tier (Autonomous)** | ${safeCount} |
| 🟡 **Caution Tier (Review Flagged)** | ${cautionCount} |
| ⚠️ **Manual Review Items (No Patch)** | ${manualIssues.length} |
| ℹ️ **AI-Dependent Items (Deferred)** | ${aiIssues.length} |

---

### 🛠️ Remediated Violations

`;

  if (appliedPatches.length === 0) {
    body += `*No automated patches were applied.*\n\n`;
  } else {
    body += `| File | Line | Rule | WCAG | Safety | Details |
| :--- | :--- | :--- | :--- | :--- | :--- |
`;
    for (const patch of appliedPatches) {
      const safetyBadge = patch.safety === 'safe' ? '🟢 `safe`' : '🟡 `caution`';
      body += `| \`${patch.file}\` | \`${patch.line || '-'}\` | \`${patch.ruleId}\` | **${patch.wcag || 'WCAG AA'}** | ${safetyBadge} | ${formatCellText(patch.message)} |\n`;
    }
    body += '\n';
  }

  // Notice for Manual Review Items (0 auto-patches applied)
  if (manualIssues.length > 0) {
    body += `---

### ⚠️ Manual Review Items (No Auto-Patch Applied)

> ⚠️ **The following violation(s) were detected but could not be safely resolved deterministically. Auto-patching was withheld to avoid incorrect edits:**

| File | Line | Rule | WCAG | Safety | Details | Status |
| :--- | :--- | :--- | :--- | :--- | :--- | :--- |
`;
    for (const issue of manualIssues) {
      body += `| \`${issue.file}\` | \`${issue.line || '-'}\` | \`${issue.ruleId}\` | **${issue.wcag || 'WCAG AA'}** | 🟡 \`caution\` | ${formatCellText(issue.message)} | ⚠️ *Manual review required (no auto-patch)* |\n`;
    }
    body += '\n';
  }

  // Fallback Notice for AI-dependent items without GEMINI_API_KEY
  if (aiIssues.length > 0) {
    body += `---

### ℹ️ AI-Assisted Remediation Notice

> ⚠️ **The following violation(s) were detected but require AI assistance. They were not auto-patched because \`GEMINI_API_KEY\` was not configured:**

| File | Line | Issue | WCAG | Status |
| :--- | :--- | :--- | :--- | :--- |
`;
    for (const issue of aiIssues) {
      const issueLabel = issue.ruleId ? `\`${issue.ruleId}\` — ${issue.message || ''}` : (issue.message || 'AI-assisted fix required');
      body += `| \`${issue.file}\` | \`${issue.line || '-'}\` | ${formatCellText(issueLabel)} | **${issue.wcag || 'WCAG AA'}** | ⏳ *Awaiting human review or Gemini API key* |\n`;
    }
    body += '\n> *To enable autonomous generation for these issues, configure the `GEMINI_API_KEY` repository secret.*\n\n';
  }

  if (diffSummary) {
    body += `---

### 🔍 Unified Patch Diffs

<details>
<summary>Click to view surgical code changes</summary>

\`\`\`diff
${diffSummary}
\`\`\`

</details>

`;
  }

  body += `---
*Generated by [fix11y](https://github.com/13Dav-arc/fix11y) — Zero-dependency surgical accessibility remediation engine.*`;

  return body;
}
